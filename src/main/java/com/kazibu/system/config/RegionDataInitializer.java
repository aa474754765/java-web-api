  @Autowired
  private RegionRepository regionRepository;

  @Override
  @Transactional
  public void run(String... args) {
    if (regionRepository.count() > 0) {
      return; // 数据已存在，跳过初始化
    }
    List<Region> regions = new ArrayList<>(800);
    initProvinces(regions);
    initCities(regions);
    initGuangdongDistricts(regions);
    regionRepository.saveAll(regions);
    System.out.println("省市区数据初始化完成，共 " + regions.size() + " 条记录");
  }

